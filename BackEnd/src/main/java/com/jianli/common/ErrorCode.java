package com.jianli.common;

import lombok.Getter;
import lombok.RequiredArgsConstructor;

/**
 * ═══════════════════════════════════════════════════════════════════════
 *  【这个类是什么】
 *  全项目所有"错误"的清单。每一种错误有一个编号、一个 HTTP 状态码、一句提示文字。
 *  它是唯一的错误来源 —— 项目里任何地方抛错，都从这里挑一个。
 * ═══════════════════════════════════════════════════════════════════════
 *
 *  【为什么要单独搞一个"错误码"，直接 throw new RuntimeException("用户名已存在") 不行吗？】
 *  不行，有三个原因：
 *
 *  1. 前端要靠它做判断。
 *     比如"用户没登录"和"密码错了"，前端要做的处理完全不同（一个跳登录页，一个提示重输）。
 *     如果只给一句中文提示，前端只能去比对字符串 —— 你哪天改了文案，前端就挂了。
 *     有了数字码，前端写 `if (code === 20002)` 就永远稳定。
 *
 *  2. 每种错误要对应不同的 HTTP 状态码。
 *     浏览器、Nginx、监控系统、日志平台，都是按 HTTP 状态码做统计的：
 *     "今天 500 有多少次" "429 涨了没"。如果所有错误都返回 200，
 *     运维那边看到的就是"一切正常"，出事了根本发现不了。
 *
 *  3. 中央管理，不会写重、写乱。
 *     所有错误集中在一个文件里，一眼看完系统有哪些失败场景。
 *     新人接手时看这一个文件就知道全貌。
 *
 *
 *  【为什么业务码和 HTTP 码要"双轨"？——这是本项目最重要的设计之一】
 *
 *     HTTP 码 → 表达"大类"（400/401/403/404/429/500...）
 *     业务码 → 表达"具体原因"（10001、20002、43002 ...）
 *
 *  举个具体的例子：为什么 43002 用 422 而不是 400？
 *
 *    43002 是"发布帖子时检测到个人信息"。
 *    400 的意思是"你的请求参数格式不对"（比如必填没填），
 *    而这里用户填的格式完全正确，只是内容不可接受 ——
 *    422 的语义正是 "Unprocessable Entity：格式没问题，但内容我处理不了"。
 *
 *    而且前端要专门针对它弹出一个"命中项 + 高亮定位"的对话框，
 *    不能用通用的 toast 提示。给它一个独立的 HTTP 码，前端拦截器一眼就能识别。
 *
 *
 *  【这个类怎么写出来的】
 *  - enum = 枚举。Java 里用来表达"一组固定的常量"，比散落各处的 int 常量安全得多。
 *  - 下面每个括号里的三个值，对应类最底下的三个字段：code、httpStatus、defaultMessage。
 *  - Lombok 的两个注解：
 *      @Getter  → 自动生成 getCode() / getHttpStatus() / getDefaultMessage()
 *      @RequiredArgsConstructor → 自动生成一个"给所有 final 字段赋值"的构造器
 *    所以 OK(0, 200, "ok") 这一行，就等于调用了那个构造器。
 *
 *
 *  【铁律】
 *  ★ 只能追加，绝不能修改已有编号的含义。
 *    前端是按数字判断的，你改了 20002 的意思，所有老前端代码都会静默出错。
 *  ★ 编号分区间，方便一眼看出是哪块业务：
 *    1xxxx 通用 / 2xxxx 账号 / 3xxxx AI / 4xxxx 简历与JD与分析
 *    43xxx 社区 / 44xxx 面试题 / 5xxxx 系统兜底
 */
@Getter
@RequiredArgsConstructor
public enum ErrorCode {

    // ═══════ 成功 ═══════
    // 为什么"成功"也要放在错误码里？
    // 因为统一响应体里 code=0 表示成功，前端拦截器要判断它。
    // 让成功和失败共用一套编号体系，判断逻辑才统一。
    OK(0, 200, "ok"),

    // ═══════ 通用 10xxx ═══════

    // @Valid 校验失败（比如 username 传了空字符串）。
    // data 里会带上"哪个字段错了、错在哪"的列表，见 GlobalExceptionHandler。
    PARAM_INVALID(10000, 400, "参数校验失败"),

    // 没带 token，或者 token 无效。
    // SecurityConfig 的 authenticationEntryPoint 会用它，返回 401。
    UNAUTHORIZED(10001, 401, "请先登录"),

    // 登录了，但操作的不是自己的数据（比如想删别人的简历）。
    FORBIDDEN(10002, 403, "无权操作该资源"),

    // 资源不存在。
    // 注意：越权访问别人的资源时，我们通常也返回"不存在"而不是"无权限"，
    // 这样不会泄露"这个 id 其实是存在的"这一信息。
    NOT_FOUND(10003, 404, "资源不存在"),

    // 429 是 HTTP 里"请求太多"的标准状态码。限流触发时用。
    TOO_MANY_REQUESTS(10004, 429, "操作过于频繁，请稍后再试"),

    // 413 = Payload Too Large，请求体超过 1MB 时用。
    PAYLOAD_TOO_LARGE(10005, 413, "提交内容过大"),

    // ═══════ 账号 20xxx ═══════

    // 409 Conflict：表示"和服务器现有状态冲突"（用户名已被别人占了）。
    // 不用 400，因为 400 是"你的格式不对"，而这里格式是对的，只是撞了。
    USERNAME_EXISTS(20001, 409, "用户名已被占用"),

    // ★ 注意这个提示语："用户名或密码错误" —— 故意不说清是哪一个。
    //   如果分开提示"用户不存在"，攻击者就能批量试用户名，先筛出哪些账号存在，
    //   再针对性爆破密码。统一提示就堵住了这条路。
    BAD_CREDENTIALS(20002, 401, "用户名或密码错误"),

    // token 解析失败 / refresh token 已作废 / 被轮换掉了。
    TOKEN_INVALID(20003, 401, "登录状态失效，请重新登录"),

    // access token 过期（但 refresh 还有效），前端应该自动刷新。
    // 目前实现里解析失败统一走 TOKEN_INVALID，这个码留给更精细的前端处理。
    TOKEN_EXPIRED(20004, 401, "登录已过期"),

    USER_NOT_FOUND(20005, 404, "用户不存在"),

    // ═══════ AI 30xxx ═══════

    // 409 而不是 501：功能是存在的，只是当前被配置关掉了，属于"状态冲突"。
    AI_DISABLED(30001, 409, "AI 功能已关闭"),

    // ★ 30xxx 全部用 5xx 而不是 4xx，原因很重要：
    //   AI 服务不可用，是【我们后端】的问题，不是【用户】的错。
    //   4xx 意味着"用户请求有问题"，5xx 意味着"服务器这边出了问题"。
    //   前端和监控都靠这个区分"该不该怪用户"。
    AI_CALL_FAILED(30002, 502, "AI 服务暂时不可用"),
    AI_TIMEOUT(30003, 504, "AI 响应超时"),
    AI_OUTPUT_INVALID(30004, 502, "AI 返回格式异常"),
    AI_QUOTA_EXCEEDED(30005, 502, "AI 调用额度不足"),

    // ═══════ 简历 40xxx ═══════
    RESUME_NOT_FOUND(40001, 404, "简历不存在"),
    VERSION_NOT_FOUND(40002, 404, "简历版本不存在"),
    // 400 而不是 404：两个版本都存在，只是不属于同一份简历，是"参数组合不合法"。
    VERSION_MISMATCH(40003, 400, "版本不属于该简历"),
    // 格式对但内容太短，属于"内容不合法"，所以用 400。
    RESUME_CONTENT_INVALID(40004, 400, "简历内容过短（至少 50 字）"),
    RESUME_ORIGINAL_NOT_FOUND(40005, 404, "该版本没有可预览的 PDF 原件"),

    // ═══════ JD 41xxx ═══════
    JD_NOT_FOUND(41001, 404, "岗位描述不存在"),
    JD_CONTENT_INVALID(41002, 400, "JD 内容过短（至少 30 字）"),

    // ═══════ 分析 42xxx ═══════
    ANALYSIS_NOT_FOUND(42001, 404, "分析报告不存在"),
    // 409：同一份简历+JD 已经在分析了，你重复提交和当前状态冲突。
    ANALYSIS_RUNNING(42002, 409, "该分析正在进行中"),
    // 500：分析失败是服务端的问题（AI 挂了、内存异常等）。
    ANALYSIS_FAILED(42003, 500, "分析失败，请重试"),
    // 400：你想看建议，但分析还没跑完，是"当前状态不允许这个操作"。
    ANALYSIS_NOT_READY(42004, 400, "分析尚未完成"),

    // ═══════ 社区 43xxx ═══════

    // 43001 和 43002 的区分是本项目的重点，一定要理解：
    //
    //   43001 → 发布失败【其他原因】（数据库写入失败等），400
    //   43002 → 发布失败【因为个人信息审核不通过】，422 ← 专用码
    //
    // 为什么要分开？因为前端处理方式完全不同：
    //   43001 → 弹一句"发布失败，请重试"
    //   43002 → 弹出对话框，列出命中的手机号/身份证，用户点一条就自动
    //           把光标定位到 textarea 里的对应位置，让用户改完再提交
    //
    // 如果合并成一个码，前端就没法知道该弹哪种 UI。
    POST_CREATE_FAILED(43001, 400, "发布失败，请稍后重试"),
    POST_PRIVACY_REJECTED(43002, 422, "内容包含个人信息，请抹去后重新发布"),

    // 409：同一份分析报告只能发一次帖，重复发和现有数据冲突。
    POST_DUPLICATED(43003, 409, "该分析结果已发布过帖子"),
    // 404 同时覆盖"不存在"和"已删除"，因为都不该让用户看到内容。
    POST_NOT_VISIBLE(43004, 404, "帖子不存在或已删除"),
    // 400：你想回复一条回复（三级），参数本身不违反格式，但业务不允许。
    COMMENT_DEPTH_EXCEEDED(43005, 400, "仅支持两级回复"),
    COMMENT_NOT_FOUND(43006, 404, "评论不存在"),
    // 400：给自己点赞，属于"操作不合业务规则"。
    SELF_VOTE_FORBIDDEN(43007, 400, "不能给自己的内容投票"),
    // 403：你确实登录了，但权限不够（只有帖子作者能采纳）。
    ADOPT_FORBIDDEN(43008, 403, "只有帖子作者可以采纳建议"),
    REPORT_NOT_OWNED(43009, 400, "报告不属于当前用户"),

    // ═══════ 面试题 44xxx ═══════
    INTERVIEW_DISABLED(44001, 409, "面试预演功能未开启"),
    INTERVIEW_GENERATION_FAILED(44002, 502, "面试题生成失败"),

    // ═══════ 兜底 ═══════
    // 所有没被上面任何一个接住的异常，最后都变成它。
    // 提示语故意写得很模糊 —— 真实的错误细节写在日志里，不能让用户看到，
    // 否则等于把内部结构暴露给攻击者。
    INTERNAL_ERROR(50000, 500, "系统繁忙，请稍后再试");

    // ──────────────────────────────────────────────────────────
    // 下面三个字段，由构造函数自动赋值（靠 Lombok 的 @RequiredArgsConstructor）
    // 因为它们是 final 的，所以枚举常量一旦创建就不能再改 —— 天然线程安全。
    // ──────────────────────────────────────────────────────────

    /** 业务码，返回给前端的 JSON 里的 code 字段。如 43002 */
    private final int code;

    /** HTTP 状态码，决定浏览器/Nginx/监控看到的状态。如 422 */
    private final int httpStatus;

    /** 默认提示语。前端可以直接显示给用户 */
    private final String defaultMessage;
}
