package com.jianli.privacy;

/**
 * ═══════════════════════════════════════════════════════════════════════
 *  【这个枚举是什么】
 *  个人信息审核要检测的类型。
 * ═══════════════════════════════════════════════════════════════════════
 *
 *  【★ 为什么只检测这几类，不检测姓名？】
 *
 *  姓名无法可靠正则化：
 *      "张三" 可能是人名，也可能是公司名、项目名、技术名词。
 *      误报后给出的拒绝理由（"你的简历里有敏感信息：张三"）用户无法理解。
 *
 *  ★ 产品上的处理：前端明确提示
 *    "发布前请自行确认姓名、公司内部信息是否需要替换为代称"。
 *    把"无法自动判断"的边界说清楚，比假装能检测更负责任。
 */
public enum SensitiveType {

    /** 手机号 */
    PHONE,

    /** 身份证号（需要校验位验证，降低误报） */
    ID_CARD,

    /** 邮箱 */
    EMAIL,

    /** 详细住址（需要"行政区划 + 门牌号"双条件） */
    ADDRESS,

    /** 银行卡号（需要 Luhn 校验） */
    BANK_CARD,

    /** 社交账号（微信/QQ） */
    SOCIAL_ACCOUNT;

    /**
     * 给用户的修改建议。
     *
     * ★ 为什么每条都给出"怎么改"而不只是"不能有"？
     *   用户知道要删，但不知道删了之后联系方式怎么办。
     *   给一个可行的替代方案（"联系方式可私信获取"），他才愿意改。
     */
    public String advice() {
        return switch (this) {
            case PHONE -> "删除手机号，或改为「联系方式可私信获取」";
            case ID_CARD -> "删除身份证号（简历不需要它）";
            case EMAIL -> "删除邮箱地址，或改为「邮箱见个人主页」";
            case ADDRESS -> "删除详细住址，只保留城市即可";
            case BANK_CARD -> "删除银行卡号";
            case SOCIAL_ACCOUNT -> "删除社交账号，或改为「可站内联系」";
        };
    }

    /** 中文显示名 */
    public String label() {
        return switch (this) {
            case PHONE -> "手机号";
            case ID_CARD -> "身份证号";
            case EMAIL -> "邮箱";
            case ADDRESS -> "详细住址";
            case BANK_CARD -> "银行卡号";
            case SOCIAL_ACCOUNT -> "社交账号";
        };
    }
}
