-- V3__add_resume_target_position.sql
--
-- 【为什么加这一列】
--   用户的核心诉求：简历列表要能一眼看出"这份简历是投什么的"。
--
--   之前 resume 表只有 title，出现的问题是：
--     用户有 3 份简历，标题分别是「社招版」「转行版」「实习版」
--     → 列表里看不出哪个投 Java、哪个投数据分析
--     → 每次都要点进去看才知道
--
--   加上 target_position 之后：
--     [Java后端-社招版]      Java 后端开发工程师      76.8分
--     [数据分析-转行版]      数据分析师                61.2分
--     [前端-实习版]          前端开发工程师            未分析
--
-- 【为什么是 VARCHAR(64) 且允许 NULL】
--   - 64 是岗位名称的合理长度（"高级 Java 后端开发工程师" = 16 字）
--   - NULL 表示"用户还没填目标岗位"，这是合法状态
--     不应该强制填写 —— 用户可以先建简历、后想清楚投什么
--
-- 【为什么不建到 job_description 的外键】
--   岗位名是用户自由输入的（"Java 后端" / "Java工程师" / "后端开发"）
--   而 job_description 是用户保存的具体 JD 记录。
--   两者粒度不同：
--     target_position = 这份简历"面向哪类岗位"（粗）
--     jd_id           = 这次分析用的"哪份具体 JD"（细）
--
--   后续版本（步骤 7 之后）可能会加 target_jd_id 做关联，
--   但那是另一个字段、另一个用途，不能互相替代。
-- =====================================================================

ALTER TABLE `resume`
  ADD COLUMN `target_position` VARCHAR(64) DEFAULT NULL
  COMMENT '目标岗位（用户填写，如 Java 后端开发工程师）'
  AFTER `title`;

