package com.jianli.resume.enums;

/**
 * ═══════════════════════════════════════════════════════════════════════
 *  【这个枚举是什么】
 *  简历版本的"来源"。记录这一版是怎么产生的。
 *
 *  库里存的是字符串（PASTE / EDIT / ADOPT_COMMENT），不是数字。
 * ═══════════════════════════════════════════════════════════════════════
 *
 *  【★ 为什么需要区分来源？】
 *
 *  版本时间线上要能看出"这一版是怎么来的"：
 *      v1  PASTE          → 初次粘贴
 *      v2  EDIT           → 自己改的
 *      v3  ADOPT_COMMENT  → 采纳了社区建议生成的
 *
 *  更重要的是，它能支撑一个很有说服力的数据：
 *      "采纳社区建议后，平均分提升了多少"
 *
 *  ★ 这个数据是产品价值的量化证明，也是面试时的亮点：
 *    "我不只做了功能，还能证明这个功能有用。"
 *
 *
 *  【★★ 为什么必须加 @Enumerated(EnumType.STRING)？】
 *
 *  这是 JPA 最经典的坑之一，一定要理解。
 *
 *  @Enumerated 有两个取值：
 *
 *    EnumType.ORDINAL（默认值！）
 *        存的是枚举的【序号】：PASTE=0, EDIT=1, ADOPT_COMMENT=2
 *        ★ 危险：如果哪天有人调整了枚举顺序，或者插入了新值
 *              （比如在 PASTE 后面加一个 UPLOAD_PDF），
 *              所有历史数据的含义都会错位 ——
 *              原来存 1 是 EDIT，现在 1 变成了 UPLOAD_PDF。
 *
 *    EnumType.STRING
 *        存的是枚举的【名字】：'PASTE' / 'EDIT' / 'ADOPT_COMMENT'
 *        ★ 安全：增删枚举值不影响已有数据。
 *
 *  ★ 所以：凡是枚举映射到数据库，一律用 STRING。
 *    这是无数团队踩过坑之后总结出的铁律。
 *
 *  【★ 为什么建表脚本里 source 默认值是 'PASTE'？】
 *  因为绝大多数版本的来源是"用户粘贴的"。给个合理默认值，
 *  即使代码某个路径忘了设置，也不会插入 null 违反 NOT NULL。
 */
public enum VersionSource {

    /** 初次粘贴（创建简历时的 v1） */
    PASTE,

    /** 用户手动编辑（在详情页改内容后保存为新版本） */
    EDIT,

    /**
     * 采纳社区评论后生成（步骤 14）
     *
     * ★ 这一版的特别之处：它是由"社区建议"驱动的，
     *   而且会带上 changeNote 说明采纳了哪条评论。
     */
    ADOPT_COMMENT
}
