package com.jianli.user.dto;

import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Pattern;
import jakarta.validation.constraints.Size;

/**
 * ═══════════════════════════════════════════════════════════════════════
 *  【这个类是什么】
 *  修改密码的请求体。需要提供旧密码 + 新密码。
 *
 *      PUT /api/users/me/password
 *      {"oldPassword":"Passw0rd1","newPassword":"NewPassw0rd2"}
 * ═══════════════════════════════════════════════════════════════════════
 *
 *  【★ 为什么必须要旧密码？】
 *
 *  三种方案对比：
 *
 *  ❌ 只要新密码
 *      风险：如果用户没锁屏、别人拿到他的电脑，就能直接改密码然后
 *            把真正的用户锁在外面。这是"会话劫持"的常见利用方式。
 *
 *  ✅ 要旧密码（本项目）
 *      改密码是高危操作，要求重新证明"你知道密码"。
 *      即使 token 被盗，攻击者也改不了密码。
 *
 *  ⚠️ 加邮件验证码
 *      最安全，但需要邮件服务。本项目不做。
 *
 *  ★ 这条规则在很多安全规范里都是硬性要求。
 *
 *  【★ 改密码之后系统会做什么？】
 *
 *  ★★ 关键：踢掉所有设备。
 *
 *      UserService.changePassword 里会调：
 *          tokenService.revokeAllRefresh(userId)
 *
 *      效果：这个用户在【所有设备】上的 refresh token 全部作废，
 *            下次刷新时失败，被迫重新登录。
 *
 *      为什么必须这样做？
 *        改密码往往意味着"我怀疑账号被盗了"。
 *        如果不踢掉其他会话，攻击者的 token 还能继续用 ——
 *        改密码就等于没改。
 * ═══════════════════════════════════════════════════════════════════════
 */
public record ChangePasswordRequest(

        /**
         * 旧密码（用来验证身份）。
         *
         * ★ 为什么只校验非空，不限长度和格式？
         *   因为它的作用是"证明你是本人"，格式对不对由比对结果决定。
         *   如果这里限制"必须 8 位"，而用户的旧密码更短（历史遗留），
         *   就会出现"密码明明是对的，却提示格式错误"的奇怪体验。
         *
         * ★ 同理，不要在这里做"新旧密码不能相同"的校验 ——
         *   那属于业务规则，放在 Service 里更合适（能返回更精确的错误码）。
         */
        @NotBlank(message = "请输入原密码")
        String oldPassword,

        /**
         * 新密码。
         *
         * ★ 校验规则必须和注册时【完全一致】：
         *   8-32 位、必须同时含字母和数字。
         *
         *   为什么不一致会有问题？
         *   如果注册要求严格、改密码允许宽松，用户就能把密码改成 "123456"，
         *   绕过注册时的安全策略。所以两处规则必须同步。
         *
         * ★ 这是个容易被忽略的点：**同一个字段在不同接口的校验规则要一致**。
         *   如果哪天要改密码规则，一定要同时改 RegisterRequest 和这里。
         *
         * ★ 要不要 CheckOldPassword 和 newPassword 不能相同？
         *   这是个产品决策。本项目不做这个校验 ——
         *   用户有权把密码改动一个字再改回来。
         *   如果要做，在 Service 里加一个判断即可。
         */
        @NotBlank(message = "请输入新密码")
        @Size(min = 8, max = 32, message = "密码长度必须在 8-32 位之间")
        @Pattern(regexp = "^(?=.*[A-Za-z])(?=.*\\d).+$", message = "密码必须同时包含字母和数字")
        String newPassword
) {}
