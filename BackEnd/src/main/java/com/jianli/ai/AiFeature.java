package com.jianli.ai;

/**
 * ═══════════════════════════════════════════════════════════════════════
 *  【这个枚举是什么】
 *  AI 能力的分类。每个功能可以单独开关。
 * ═══════════════════════════════════════════════════════════════════════
 *
 *  【★ 为什么分功能而不是一个总开关？】
 *
 *  总开关适合"整个环境都不开 AI"（本地开发、CI、演示）。
 *  分功能适合"AI 开着，但某个功能先不上线"：
 *      比如面试题还在调 Prompt，就先设 interview: false，
 *      用户看不到入口，其他功能不受影响。
 *
 *  ★ 两级结合：必须【总开关开 且 分开关开】才真正可用。
 */
public enum AiFeature {

    /** JD 结构化解析 */
    JD_PARSE,

    /** 简历结构化解析 */
    RESUME_PARSE,

    /** 板块改进建议 */
    SUGGESTIONS,

    /** AI 简历重写（逐条） */
    REWRITE,

    /** 面试预演题 */
    INTERVIEW,

    /** 个人信息审核的 AI 辅助（默认关闭） */
    PRIVACY_ASSIST
}
