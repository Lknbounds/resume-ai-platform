package com.jianli.resume.dto;

import java.time.LocalDateTime;

/**
 * ═══════════════════════════════════════════════════════════════════════
 *  【这个类是什么】
 *  简历列表里的"一行"。不含正文、不含版本详情。
 *
 *  返回的 JSON：
 *      {
 *        "id": 10, "title": "Java 后端简历",
 *        "versionCount": 3, "currentVersionId": 35,
 *        "currentVersionPreview": "张三 | 后端开发 教育背景：...",
 *        "updatedAt": "2026-11-16 21:10:00"
 *      }
 * ═══════════════════════════════════════════════════════════════════════
 *
 *  【★ 为什么简历列表也要单独一个 VO？】
 *
 *  简历实体只有 7 个字段，看起来"直接返回实体也没多大"。
 *  但有几个问题：
 *
 *  1. 【updatedAt 和 createdAt 都返回，但列表只需要 updatedAt】
 *     多一个字段就是多一份解析开销，虽然很小，但没必要。
 *
 *  2. 【将来会加派生字段】
 *     比如"最新得分"、"最近分析的岗位"——这些不是 Resume 的字段，
 *     是查了 report 表算出来的。只能放 VO 里。
 *
 *  3. 【一致性】
 *     项目里所有对外返回都用 VO，不搞"这个能省就省"的特殊情况。
 *     ★ 规则统一比"每个都优化到极致"更重要 —— 后者会让代码不可预测。
 *
 *
 *  【★ currentVersionPreview 是干嘛的？】
 *
 *  列表里显示简历的"前几十个字"，让用户一眼辨认是哪份简历。
 *  只有标题的话，如果用户有两份都叫"Java 简历"，就分不清了。
 *
 *  ★ 为什么叫 Preview？
 *    因为它是截断的（前 60 字左右）。
 *    完整内容在详情页看。
 */
public record ResumeSummaryVO(

        /** 简历 id。点进详情用它 */
        Long id,

        /** 标题 */
        String title,

        /**
         * 目标岗位。★ 可为 null。
         *
         * 【★ 这是列表里最重要的新增字段】
         *
         *  用户有 3 份简历时，光看标题分不清：
         *      「社招版」「转行版」「实习版」
         *
         *  加上岗位后：
         *      [Java后端-社招版]   → Java 后端开发工程师   76.8分
         *      [数据分析-转行版]   → 数据分析师             61.2分
         *      [前端-实习版]       → 前端开发工程师         未分析
         *
         *  ★ 这就是用户说的"不同岗位改好的成品简历"在列表上的样子。
         */
        String targetPosition,

        /**
         * 当前版本 id。
         *
         * ★ 为什么列表也要返回它？
         *   因为"发起分析"时要选一个版本。
         *   用户从列表直接点"分析"，前端需要知道默认用哪一版 ——
         *   就是当前版本。
         *
         *   有它就不需要先调详情接口拿版本列表。
         */
        Long currentVersionId,

        /** 版本数。显示成 "3 个版本" */
        Integer versionCount,

        /**
         * 当前版本的前 60 字预览。
         *
         * ★ 由 Service 填写，从当前版本的 content 截取。
         *   如果版本已被删除或查不到，就是 null。
         *
         * ★ 为什么要在这里做截断而不是让前端做？
         *   因为不能把完整正文传给前端（体积问题）。
         *   ★ 截断必须在【数据离开数据库之后、但离开服务器之前】做。
         */
        String currentVersionPreview,

        /**
         * 最新一次分析的总分。★ 没有分析过时为 null。
         *
         * 【★ 这是列表里最重要的信息之一】
         *
         *  用户看简历列表时最想知道的是"这份投出去行不行"。
         *  分数直接给出答案，不用点进去看。
         *
         * ★ 数据来源：analysis_report 表里该版本最近一次 SUCCESS/PARTIAL 的报告。
         *   由 ResumeService.list 批量查询后填充（避免 N+1）。
         */
        Double latestScore,

        /** 最新报告 id，前端可用它直接打开对应岗位的分析报告。 */
        Long latestReportId,

        /**
         * 最新一次分析用的岗位名。
         *
         * ★ 为什么需要它？
         *   简历的 targetPosition 是"我打算投这个岗"，
         *   而 latestJdTitle 是"我实际拿哪个 JD 分析的"。
         *   两者可能不同（用户建简历时没填岗位，分析时才选）。
         */
        String latestJdTitle,

        /** 最新一次分析对应岗位的公司，可能为空。 */
        String latestJdCompany,

        /** 最新一次完成分析的时间。 */
        LocalDateTime latestAnalyzedAt,

        /** 当前简历版本一共分析过多少个不同岗位。 */
        Integer analyzedJdCount,

        /**
         * 最后更新时间。
         *
         * ★ 它有三重含义：
         *   1. 改过标题
         *   2. 加过新版本
         *   3. 列表按它倒序排（最近在改的排前面）
         */
        LocalDateTime updatedAt

        /*
         * ═══════════════════════════════════════════════════════════
         *  【★ 后续步骤会往这里加什么】
         *
         *  步骤 15 之后（有了面试题）：
         *      Integer questionSetCount  生成过几批面试题
         *    用于简历卡片上显示"有 2 套面试题"。
         * ═══════════════════════════════════════════════════════════
         */
) {}
