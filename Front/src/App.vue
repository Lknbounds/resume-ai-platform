<script setup>
/**
 * ═══════════════════════════════════════════════════════════════════════
 *  【这个文件是什么】
 *  根组件。里面只有一行 <router-view />。
 *
 *  ★ 为什么这么简单？
 *    因为页面的结构差异很大：
 *       登录页 → 居中卡片，没有导航栏
 *       业务页 → 顶部导航 + 内容区
 *    所以导航栏不放在这里，而是放在 layouts/DefaultLayout.vue 里，
 *    由需要导航栏的页面自己包一层。
 *
 *  ★ 另一种做法是"布局组件 + router-view 嵌套"，
 *    但那样要在路由表里配置 children，稍复杂。
 *    本项目页面数量不多，手动包 DefaultLayout 更直观。
 * ═══════════════════════════════════════════════════════════════════════
 *
 *  【★ router-view 是什么】
 *  它是"路由出口"——Vue Router 会根据当前 URL 把对应组件渲染到那个位置。
 *
 *      访问 /login   → 这里显示 LoginView
 *      访问 /        → 这里显示 DashboardView
 */
</script>

<template>
  <router-view />
</template>
